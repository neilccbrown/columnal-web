#!/usr/bin/env python3
# Copies the table-reading part of the ORIGINAL HTMLImporter.importTable (from reading the table's
# rows to making the ImportPlainTable for it, without the import dialog) into a class
# xyz.columnal.importers.HTMLTableReader, for ImportersHarness.java.  HTMLImporter itself builds
# JavaFX dialogs, so the golden build doesn't compile it.
#   extract-html-table-reader.py <HTMLImporter.java with annotations stripped> <output .java>
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
lines = src.split("\n")

start = next(i for i, l in enumerate(lines) if "final List<ArrayList<String>> vals = new ArrayList<>();" in l)
end = next(i for i, l in enumerate(lines) if i > start and "results.add(new FXPlatformSupplier" in l)
body = lines[start:end]

# Remove getGUI from the anonymous ImportPlainTable (it builds the dialog's check boxes):
gui = next(i for i, l in enumerate(body) if "public Node getGUI()" in l)
depth = 0
started = False
for j in range(gui, len(body)):
    depth += body[j].count("{") - body[j].count("}")
    if "{" in body[j]:
        started = True
    if started and depth == 0:
        break
body = body[:gui] + body[j + 1:]
body = [l for l in body if not re.match(r"\s*LabelledGrid labelledGrid;\s*$", l)]

imports = [l for l in lines if l.startswith("import ") and not re.match(r"import (javafx|org\.w3c|xyz\.columnal\.utility\.gui|xyz\.columnal\.importers\.gui)", l)]
footnote = next(l for l in lines if "FOOTNOTE_REGEX =" in l)

out = ["// Generated by scripts/golden/extract-html-table-reader.py from the original HTMLImporter.java.",
       "package xyz.columnal.importers;", ""] + imports + ["",
       "public class HTMLTableReader", "{", footnote, "    private enum TableState { HEAD, BODY };", "",
       "    public static ImportPlainTable readTable(TableManager mgr, Element table, boolean fromWikipedia, List<List<String>> valsOut, List<String> columnNamesOut)",
       "    {"] + body + [
       "        valsOut.addAll(vals);",
       "        columnNamesOut.addAll(columnNames);",
       "        return imp;",
       "    }", "",
       "    // ImportPlainTable is package-private, so the harness reads its PlainImportInfo with this:",
       "    public static Pair<TrimChoice, ImmutableList<ColumnInfo>> plainImportInfo(Object format)",
       "    {",
       "        if (!(format instanceof PlainImportInfo))",
       "            return null;",
       "        return new Pair<>(((PlainImportInfo) format).trim, ((PlainImportInfo) format).columnInfo);",
       "    }", "}", ""]
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out))
