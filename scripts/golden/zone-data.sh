#!/usr/bin/env bash
# Extracts java.time's zone ID list and short zone-name table (en-US) from the JVM into
# src/engine/java/time/JavaZoneData.ts, so zone parsing matches Java exactly.
# Usage: scripts/golden/zone-data.sh   (needs Java 17+)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/src/engine/java/time/JavaZoneData.ts"
DATA="$(java -Duser.language=en -Duser.country=US "$ROOT/scripts/golden/java/ZoneDataHarness.java")"
JAVA_VERSION="$(java -version 2>&1 | head -1)"
{
    echo "// GENERATED by scripts/golden/zone-data.sh from $JAVA_VERSION -- do not edit."
    echo "// The time-zone IDs java.time knows, and how java.time's appendZoneText(TextStyle.SHORT)"
    echo "// parses zone names in the en-US locale (e.g. \"EST\" -> America/New_York)."
    echo ""
    echo "export const JAVA_ZONE_IDS: readonly string[] = ["
    echo "$DATA" | grep '^id ' | sed -E 's/^id (.*)$/    "\1",/'
    echo "];"
    echo ""
    echo "export const JAVA_SHORT_ZONE_NAMES: ReadonlyMap<string, string> = new Map(["
    echo "$DATA" | grep '^short ' | sed -E 's/^short ([^ ]*) (.*)$/    ["\1", "\2"],/'
    echo "]);"
} > "$OUT"
echo "$(grep -c '^    "' "$OUT") zone IDs and $(grep -c '^    \[' "$OUT") zone names written to $OUT"
